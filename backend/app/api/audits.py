"""
Audit endpoints.

POST /audits                    — start a new audit
GET  /audits/{id}/stream        — SSE stream of live turns
GET  /audits/{id}/turns         — polling fallback: all turns + verdicts
GET  /audits/{id}/debrief       — completed debrief card
"""

import asyncio
import json
import logging
import threading
import uuid

from fastapi import APIRouter, HTTPException, Depends, Request
from sse_starlette.sse import EventSourceResponse

from app.api.dependencies import get_session_id
from app.constants import ROUND_TOPICS
from app.database import get_supabase
from app.models.schemas import (
    AuditCreateRequest,
    AuditCreateResponse,
    TurnsListResponse,
    TurnResponse,
    VerdictResponse,
    DebriefCardResponse,
    ErrorResponse,
)
from app.agents.graph import run_audit

logger = logging.getLogger(__name__)
router = APIRouter(tags=["audits"])

# ---------------------------------------------------------------------------
# In-process concurrency: one audit at a time to respect Gemini rate limits.
# ---------------------------------------------------------------------------
_audit_lock = threading.Lock()

# Active SSE queues, keyed by audit_id.
# Each value is an asyncio.Queue that the graph pushes events onto.
_sse_queues: dict[str, asyncio.Queue] = {}

# Reference to the main event loop (set during app lifespan).
_event_loop: asyncio.AbstractEventLoop | None = None


def set_event_loop(loop: asyncio.AbstractEventLoop) -> None:
    """Called once from main.py lifespan to capture the loop reference."""
    global _event_loop
    _event_loop = loop


# ---------------------------------------------------------------------------
# POST /audits
# ---------------------------------------------------------------------------
@router.post(
    "/audits",
    response_model=AuditCreateResponse,
    responses={400: {"model": ErrorResponse}},
)
async def create_audit(
    body: AuditCreateRequest,
    session_id: str = Depends(get_session_id),
):
    """Start a new audit for a paper + round topic."""
    # Validate topic
    if body.round_topic not in ROUND_TOPICS:
        raise HTTPException(
            status_code=400,
            detail=f"Invalid round_topic '{body.round_topic}'. "
            f"Must be one of: {list(ROUND_TOPICS.keys())}",
        )

    # Verify paper exists
    supabase = get_supabase()
    paper = supabase.table("papers").select("id").eq("id", body.paper_id).execute()
    if not paper.data:
        raise HTTPException(status_code=404, detail="Paper not found")

    # Create audit + round rows
    audit_id = str(uuid.uuid4())
    round_id = str(uuid.uuid4())

    supabase.table("audits").insert({
        "id": audit_id,
        "paper_id": body.paper_id,
        "session_id": session_id,
        "round_topic": body.round_topic,
        "strictness_level": "standard",
        "depth": "fast",
        "status": "in_progress",
    }).execute()

    supabase.table("rounds").insert({
        "id": round_id,
        "audit_id": audit_id,
        "round_number": 1,
        "topic": body.round_topic,
        "status": "in_progress",
    }).execute()

    # Set up SSE queue
    queue: asyncio.Queue = asyncio.Queue()
    _sse_queues[audit_id] = queue

    # Create the SSE callback that pushes events from the graph thread
    # into the asyncio queue (thread-safe).
    loop = _event_loop or asyncio.get_event_loop()

    def sse_callback(event: dict) -> None:
        loop.call_soon_threadsafe(queue.put_nowait, event)

    # Launch the graph in a background thread.
    def _run():
        with _audit_lock:
            try:
                run_audit(body.paper_id, round_id, body.round_topic, sse_callback)
            except Exception as exc:
                logger.exception("Audit %s failed: %s", audit_id, exc)
            finally:
                # Signal stream completion
                loop.call_soon_threadsafe(queue.put_nowait, None)

    thread = threading.Thread(target=_run, daemon=True)
    thread.start()

    logger.info("Audit %s started (topic: %s)", audit_id, body.round_topic)

    return AuditCreateResponse(
        audit_id=audit_id,
        round_id=round_id,
        status="in_progress",
    )


