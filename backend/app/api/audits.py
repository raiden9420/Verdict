# GET /audits/{audit_id}/turns — polling fallback
# ---------------------------------------------------------------------------
@router.get(
    "/audits/{audit_id}/turns",
    response_model=TurnsListResponse,
)
async def list_turns(audit_id: str):
    """
    Polling fallback — returns all turns and verdicts so far.
    Used when the SSE connection drops.
    """
    supabase = get_supabase()

    # Get audit
    audit = supabase.table("audits").select("status").eq("id", audit_id).execute()
    if not audit.data:
        raise HTTPException(status_code=404, detail="Audit not found")

    # Get round(s) for this audit
    rounds = supabase.table("rounds").select("id").eq("audit_id", audit_id).execute()
    if not rounds.data:
        return TurnsListResponse(turns=[], verdicts=[], status=audit.data[0]["status"])

    round_ids = [r["id"] for r in rounds.data]

    # Get all turns
    turns_data = (
        supabase.table("turns")
        .select("*")
        .in_("round_id", round_ids)
        .order("exchange_number")
        .order("sequence")
        .execute()
    )

    # Get all verdicts
    verdicts_data = (
        supabase.table("verdicts")
        .select("*")
        .in_("round_id", round_ids)
        .order("exchange_number")
        .execute()
    )

    turns = []
    for t in (turns_data.data or []):
        content = t["content"]
        if isinstance(content, str):
            try:
                content = json.loads(content)
            except (json.JSONDecodeError, TypeError):
                pass
        turns.append(TurnResponse(
            id=t["id"],
            exchange_number=t["exchange_number"],
            agent_type=t["agent_type"],
            sequence=t["sequence"],
            content=content,
            created_at=t.get("created_at", ""),
        ))

    verdicts = []
    for v in (verdicts_data.data or []):
        cited = v.get("cited_chunk_ids")
        if isinstance(cited, str):
            try:
                cited = json.loads(cited)
            except (json.JSONDecodeError, TypeError):
                pass
        verdicts.append(VerdictResponse(
            id=v["id"],
            exchange_number=v["exchange_number"],
            claim_summary=v.get("claim_summary"),
            verdict_type=v["verdict_type"],
            confidence=v.get("confidence"),
            rationale=v.get("rationale"),
            cited_chunk_ids=cited,
        ))

    return TurnsListResponse(
        turns=turns,
        verdicts=verdicts,
        status=audit.data[0]["status"],
    )


# ---------------------------------------------------------------------------
# GET /audits/{audit_id}/debrief
# ---------------------------------------------------------------------------
@router.get(
    "/audits/{audit_id}/debrief",
    response_model=DebriefCardResponse,
    responses={404: {"model": ErrorResponse}},
)
async def get_debrief(audit_id: str):
    """Return the completed Debrief Card, or 404 if not yet generated."""
    supabase = get_supabase()

    # Get round for this audit
    rounds = supabase.table("rounds").select("id").eq("audit_id", audit_id).execute()
    if not rounds.data:
        raise HTTPException(status_code=404, detail="No round found for this audit")

    round_id = rounds.data[0]["id"]

    debrief = (
        supabase.table("debrief_cards")
        .select("*")
        .eq("round_id", round_id)
        .execute()
    )

    if not debrief.data:
        raise HTTPException(
            status_code=404,
            detail="Debrief card not yet generated — audit may still be in progress.",
        )

    d = debrief.data[0]

    # Parse JSON fields if stored as strings
    for field in ("solidified_strengths", "actionable_weaknesses", "contested_points"):
        val = d.get(field)
        if isinstance(val, str):
            try:
                d[field] = json.loads(val)
            except (json.JSONDecodeError, TypeError):
                d[field] = []

    # Fetch paper_id and topic to attach reproducibility_checklist if relevant
    reproducibility_checklist = None
    try:
        audit_res = supabase.table("audits").select("paper_id, round_topic").eq("id", audit_id).execute()
        if audit_res.data:
            paper_id = audit_res.data[0].get("paper_id")
            topic = audit_res.data[0].get("round_topic")
            if topic == "reproducibility" and paper_id:
                paper_res = supabase.table("papers").select("reproducibility_signals").eq("id", paper_id).execute()
                if paper_res.data and paper_res.data[0].get("reproducibility_signals"):
                    reproducibility_checklist = paper_res.data[0]["reproducibility_signals"]
    except Exception as exc:
        logger.warning("Could not fetch reproducibility checklist for debrief: %s", exc)

    return DebriefCardResponse(
        id=d["id"],
        executive_synthesis=d.get("executive_synthesis"),
        solidified_strengths=d.get("solidified_strengths"),
        actionable_weaknesses=d.get("actionable_weaknesses"),
        contested_points=d.get("contested_points"),
        reproducibility_checklist=reproducibility_checklist,
    )

