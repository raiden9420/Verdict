# GET /audits/{audit_id}/stream — SSE
# ---------------------------------------------------------------------------
@router.get("/audits/{audit_id}/stream")
async def stream_audit(audit_id: str, request: Request):
    """
    Server-Sent Events stream of turns, verdicts, and the debrief card
    as they are generated by the agent graph.
    """
    queue = _sse_queues.get(audit_id)
    if queue is None:
        # Audit might already be done — check DB status
        supabase = get_supabase()
        audit = supabase.table("audits").select("status").eq("id", audit_id).execute()
        if not audit.data:
            raise HTTPException(status_code=404, detail="Audit not found")
        if audit.data[0]["status"] == "completed":
            raise HTTPException(
                status_code=410,
                detail="Audit already completed. Use /turns and /debrief instead.",
            )
        raise HTTPException(status_code=404, detail="SSE stream not available")

    async def event_generator():
        try:
            while True:
                # Check if client disconnected
                if await request.is_disconnected():
                    break

                try:
                    event = await asyncio.wait_for(queue.get(), timeout=30)
                except asyncio.TimeoutError:
                    # Send heartbeat to keep connection alive
                    yield {"event": "heartbeat", "data": "{}"}
                    continue

                if event is None:
                    # Stream complete
                    yield {"event": "complete", "data": "{}"}
                    break

                event_type = event.get("type", "message")
                event_data = json.dumps(event.get("data", {}))
                yield {"event": event_type, "data": event_data}

        finally:
            # Clean up the queue
            _sse_queues.pop(audit_id, None)

    return EventSourceResponse(event_generator())


